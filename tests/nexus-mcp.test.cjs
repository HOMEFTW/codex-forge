'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const readline = require('node:readline');
const { spawn } = require('node:child_process');
const { NexusService } = require('../runtime/nexus.cjs');
test('real MCP exposes Nexus, enforces revisions, returns actual file changes, and blocks disabled plugin', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-mcp-')), vault = path.join(root, 'vault'), forge = path.join(root, 'forge'), store = path.join(root, 'store');
  fs.mkdirSync(vault); fs.mkdirSync(forge); fs.writeFileSync(path.join(vault, '首页.md'), '# MCP 知识库\n');
  const config=require('../forge.config.json');
  const {ForgeRegistry}=require('../runtime/forge-registry.cjs');
  const registry=new ForgeRegistry({root:forge,bundledRoot:path.join(root,'empty'),versions:{codex:config.codexVersion,forge:config.version,apiVersion:config.apiVersion}});
  const plugin=path.join(root,'plugin');fs.mkdirSync(plugin);
  const manifest={schemaVersion:1,apiVersion:3,id:'homeftw.nexus',name:'Nexus',version:'0.1.0',compatibility:{codex:[config.codexVersion],forge:['>=0.4.0 <0.6.0']},permissions:['nexus.read','nexus.write'],capabilities:[{name:'nexus',version:1}]};
  fs.writeFileSync(path.join(plugin,'plugin.json'),JSON.stringify(manifest));
  const service = new NexusService({ root: path.join(store, 'nexus') }), vaultId = service.connect(vault).vault.id;
  const child = spawn(process.env.FAST_TEST_NODE || process.execPath, [path.resolve(__dirname, '../runtime/mcp.cjs')], { env: { ...process.env, CODEX_FAST_CANVAS_DIR: store, CODEX_FORGE_HOME: forge }, windowsHide: true });
  t.after(() => { child.kill(); fs.rmSync(root, { recursive: true, force: true }); });
  const pending = new Map(); let id = 0, stderr = ''; child.stderr.on('data', b => { stderr += b; });
  readline.createInterface({ input: child.stdout }).on('line', line => { const reply = JSON.parse(line); pending.get(reply.id)?.(reply); pending.delete(reply.id); });
  const request = (method, params) => new Promise((resolve, reject) => { const n = ++id, timer = setTimeout(() => reject(Error(stderr || 'MCP timeout')), 10000); pending.set(n, value => { clearTimeout(timer); resolve(value); }); child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: n, method, params }) + '\n'); });
  const call = async (name, args = {}) => (await request('tools/call', { name, arguments: args })).result;
  const initialized = await request('initialize', { protocolVersion: '2025-03-26' }); assert.equal(initialized.result.serverInfo.version, config.version);
  assert(!(await request('tools/list')).result.tools.some(t=>t.name.startsWith('nexus_')));
  assert((await call('nexus_vaults')).isError);
  registry.install(plugin);
  assert(!(await request('tools/list')).result.tools.some(t=>t.name.startsWith('nexus_')));
  registry.setEnabled(manifest.id,true);
  const names = (await request('tools/list')).result.tools.map(t => t.name); assert(names.includes('nexus_write')); assert(!names.some(n => n.startsWith('obsidian_')));
  const listed = JSON.parse((await call('nexus_vaults')).content[0].text); assert.equal(listed.vaults[0].id, vaultId);
  const doc = JSON.parse((await call('nexus_read', { vaultId, path: '首页.md' })).content[0].text);
  const written = await call('nexus_write', { vaultId, path: doc.path, expectedRevision: doc.revision, content: '# 模型更新\n' }); assert(!written.isError);
  assert.equal(fs.readFileSync(path.join(vault, '首页.md'), 'utf8'), '# 模型更新\n');
  const conflict = await call('nexus_write', { vaultId, path: doc.path, expectedRevision: doc.revision, content: 'stale' }); assert(conflict.isError);
  const deniedConnect = await call('nexus_browse', { vaultId, method: 'connect', root: vault }); assert(deniedConnect.isError);
  registry.setEnabled(manifest.id,false);
  assert(!(await request('tools/list')).result.tools.some(t => t.name.startsWith('nexus_')));
  assert((await call('nexus_read', { vaultId, path: doc.path })).isError);
  registry.setEnabled(manifest.id,true);
  const installed=path.join(forge,'plugins',manifest.id,'plugin.json');
  fs.writeFileSync(installed,JSON.stringify({...manifest,permissions:['nexus.read']}));
  assert(!(await request('tools/list')).result.tools.some(t=>t.name.startsWith('nexus_')),'modified fingerprint revokes tools');
  registry.reload();registry.setEnabled(manifest.id,true);
  const readOnlyNames=(await request('tools/list')).result.tools.map(t=>t.name);
  assert(readOnlyNames.includes('nexus_read'));assert(!readOnlyNames.includes('nexus_write'));
  assert((await call('nexus_write',{vaultId,path:doc.path,content:'denied',expectedRevision:''})).isError);
  assert(!(await call('nexus_read',{vaultId,path:doc.path})).isError);
  registry.uninstall(manifest.id);
  assert(!(await request('tools/list')).result.tools.some(t=>t.name.startsWith('nexus_')));
  assert((await call('nexus_read',{vaultId,path:doc.path})).isError);
  child.stdin.end(); await new Promise(resolve => child.on('exit', resolve));
});
